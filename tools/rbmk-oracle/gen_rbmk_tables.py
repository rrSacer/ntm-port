#!/usr/bin/env python3
"""Regenerates crates/ntm-core/src/rbmk/tables_data.rs:
 - HEATABLES: every fluid with FT_Heatable in Fluids.java (heat-exchanger
   efficiency, first heating step, produced fluid and its temperature),
 - OUTGASSER: the 19 default outgasser recipes, from fixtures/java.json (the
   executed OutgasserRecipes.registerDefaults()).
Both are plain data; the heater and outgasser behaviour is compared with the
oracle, and the heatable rows are re-derived from the pinned source in
tests/rbmk_tables.rs' companion check (run this script with --check)."""
import json, pathlib, re, sys
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SRC = pathlib.Path('/mnt/ssd120/sacer/horizon-ntm/ntm-src/src/main/java/com/hbm/inventory/fluid/Fluids.java')


def clean(t):
    return re.sub(r'"(?:\\.|[^"\\])*"|//[^\n]*|/\*.*?\*/', lambda m: m[0] if m[0][0] == '"' else re.sub(r'[^\n]', ' ', m[0]), t, flags=re.S)


def rust_f(x):
    return repr(float(x))


def heatables():
    text = SRC.read_text()
    c = clean(text)
    temps = {}
    for d in re.finditer(r'^\s*([A-Z0-9_]+)\s*=\s*new FluidType\(([^;]*);', c, re.M):
        t = re.search(r'\.setTemp\(([\d_]+)\)', d[2])
        temps[d[1]] = int(t[1].replace('_', '')) if t else 20
    consts = {m[1]: float(m[2]) for m in re.finditer(r'double (eff_\w+) = ([0-9.]+)D;', c)}
    rows = []
    for m in re.finditer(r'^\s*([A-Z0-9_]+)\.addTraits\(new FT_Heatable\(\)', c, re.M):
        end = c.index(';\n', m.start())
        stmt = c[m.start():end]
        heat = [x for x in stmt.split('FT_Heatable()')[1].split('new FT_')[0:1]][0]
        eff = re.search(r'setEff\(HeatingType\.HEATEXCHANGER,\s*([\w.]+?)D?\)', heat)
        value = 0.0
        if eff:
            value = consts[eff[1]] if eff[1] in consts else float(eff[1])
        step = re.search(r'addStep\((\d+),\s*(\d+),\s*([A-Z0-9_]+),\s*(\d+)\)', heat)
        rows.append((m[1], value, int(step[2]), int(step[1]), step[3], int(step[4]), temps[step[3]]))
    return rows, temps


def outgasser():
    d = json.load(open(HERE / 'fixtures/java.json'))
    return d['recipes']['outgasser_defaults']


def main():
    rows, temps = heatables()
    out = ['// @generated by tools/rbmk-oracle/gen_rbmk_tables.py; do not edit.',
           'use super::outgasser::{OutgasserInput, OutgasserRecipe};', '',
           '/// `(fluid, heat-exchanger efficiency, amountReq, heatReq, produced fluid, amountProduced, produced temperature)`',
           '/// of the first step of every `FT_Heatable`; efficiency 0 when the trait has no heat-exchanger value.',
           'pub const HEATABLES: [(&str, f64, i32, i32, &str, i32, i32); %d] = [' % len(rows)]
    for r in rows:
        out.append('    ("%s", %s, %d, %d, "%s", %d, %d),' % (r[0], rust_f(r[1]), r[2], r[3], r[4], r[5], r[6]))
    out.append('];\n')
    rec = outgasser()
    out.append('pub const OUTGASSER: [OutgasserRecipe; %d] = [' % len(rec))
    for r in rec:
        i = r['input']
        inp = ('OutgasserInput::Ore("%s")' % i['ore']) if 'ore' in i else 'OutgasserInput::Stack("%s", %d)' % (i['stack']['item'], i['stack']['meta'])
        s = r['solid']
        solid = 'Some(("%s", %d, %d))' % (s['item'], s['count'], s['meta']) if s else 'None'
        f = r['fluid']
        fluid = 'Some(("%s", %d))' % (f['type'], f['amount']) if f else 'None'
        out.append('    OutgasserRecipe { input: %s, solid: %s, fluid: %s, fusion_only: %s },' % (inp, solid, fluid, 'true' if r['fusion_only'] else 'false'))
    out.append('];')
    text = '\n'.join(out) + '\n'
    path = ROOT / 'crates/ntm-core/src/rbmk/tables_data.rs'
    import subprocess, tempfile
    with tempfile.TemporaryDirectory() as tmp:
        scratch = pathlib.Path(tmp) / 'tables_data.rs'
        scratch.write_text(text)
        subprocess.run(['rustfmt', '--edition', '2021', str(scratch)], check=True)  # the repo is rustfmt-clean
        text = scratch.read_text()
    if '--check' in sys.argv:
        assert path.read_text() == text, 'tables_data.rs is stale'
    else:
        path.write_text(text)
    print(len(rows), 'heatables,', len(rec), 'outgasser recipes')


main()
