#!/usr/bin/env python3
"""Regenerate crates/ntm-core/src/rbmk/rods_data.rs from fixtures/java.json.

The table is plain data (the 33 rods' fields); behavior is checked against the
oracle's per-tick traces in tests/rbmk_oracle_parity.rs, and the table itself is
re-compared to the fixture there, so drift fails the test."""
import json, pathlib, sys
root = pathlib.Path(__file__).resolve().parents[2]
d = json.load(open(root / "tools/rbmk-oracle/fixtures/java.json"))

def f(x):  # exact f64 literal
    return repr(float(x)) if float(x) == float(x) else "f64::NAN"

CAMEL = lambda s: "".join(p.capitalize() for p in s.split("_"))
out = ["// @generated by tools/rbmk-oracle/gen_rods_rs.py from fixtures/java.json; do not edit.",
       "use super::rods::{BurnFunc, DepleteFunc, NType, RodType};", "",
       "pub const RODS: [RodType; %d] = [" % len(d["rods"])]
for r in d["rods"]:
    hc = r["heat_coefficient"]; nt = r["neutron_types"]
    pel = '"%s"' % r["pellet"] if r["pellet"] else "\"\""
    out.append("    RodType {")
    out.append('        variable: "%s", full_name: %s, pellet: %s,' % (r["variable"], json.dumps(r["full_name"], ensure_ascii=False), pel))
    out.append("        yield_: %s, reactivity: %s, self_rate: %s," % (f(r["yield"]), f(r["func_end"]), f(r["self_rate"])))
    out.append("        function: BurnFunc::%s, depletion: DepleteFunc::%s," % (CAMEL(r["function"]), CAMEL(r["depletion_function"])))
    out.append("        x_gen: %s, x_burn: %s, heat: %s," % (f(r["xenon_generation"]), f(r["xenon_burn_divisor"]), f(r["heat_per_flux"])))
    out.append("        melting_point: %s, diffusion: %s," % (f(r["melting_point"]), f(r["diffusion"])))
    out.append("        heat_coeff_start: %s, heat_coeff_length: %s," % (f(hc["start"]), f(hc["length"])))
    out.append("        n_type: NType::%s, r_type: NType::%s, tint: %d," % (CAMEL(nt["absorbs"]), CAMEL(nt["releases"]), r["tint"]))
    out.append("    },")
out.append("];")
(root / "crates/ntm-core/src/rbmk/rods_data.rs").write_text("\n".join(out) + "\n")
