"""Radiation resistance: crates/ntm-core/data/hazmat.json from the Java.

`HazmatRegistry.initDefault` registers every armor piece with a product of
two `double`s (`hazYellow * helmet`) or a literal; each product is evaluated
here in IEEE double, as the JVM does, so `0.6 * 0.2` stays
0.12000000000000001. `ItemModCladding(rad)` in `ModItems` gives the cladding
mods. A piece the port does not have is kept in `unported` by its Java name:
the table is ready when the item arrives, nothing is invented.

Run `python3 tools/content-gen/hazmat.py` to rewrite the file, `--check` to
compare (exit 1 if it differs).
"""
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
JAVA = Path(os.environ.get('NTM_SRC', ROOT.parent / 'ntm-src')) / 'src/main/java/com/hbm'
OUT = ROOT / 'crates/ntm-core/data/hazmat.json'
REGISTRY = 'handler/HazmatRegistry.java'
# 1.7.10 `Items` fields whose 1.21 names differ only by namespace.
VANILLA = {'iron_helmet', 'iron_chestplate', 'iron_leggings', 'iron_boots',
           'golden_helmet', 'golden_chestplate', 'golden_leggings', 'golden_boots'}


def catalog():
    entries = json.loads((ROOT / 'content/ids.json').read_text())['entries']
    return {e['source_variable']: e['id'] for e in entries
            if e.get('source_variable') and not e.get('source_enum') and not e.get('source_fluid')}


def item(expr, plain):
    """(port id or None, Java name)."""
    owner, name = expr.split('.')
    if owner == 'Items':
        return ('minecraft:' + name if name in VANILLA else None), expr
    return plain.get(name), expr


def extract():
    plain = catalog()
    text = (JAVA / REGISTRY).read_text()
    values = {}
    # The class fields (helmet, chest, legs, boots) and the locals of initDefault.
    for name, literal in re.findall(r'(?:public static )?double (\w+) = ([0-9.]+)D;', text):
        values[name] = float(literal)

    def evaluate(expr):
        factors = [f.strip() for f in expr.split('*')]
        result = None
        for f in factors:
            v = values[f] if f in values else float(f.rstrip('D'))
            result = v if result is None else result * v
        return result

    resistance, unported = {}, []
    for line_no, line in enumerate(text.splitlines(), 1):
        m = re.search(r'HazmatRegistry\.registerHazmat\((\w+\.\w+), (.+)\);', line)
        if not m or 'pair.getKey()' in line:
            continue
        port, java = item(m.group(1), plain)
        value = evaluate(m.group(2))
        row = {'value': value, 'source': f'{REGISTRY}:{line_no}'}
        if port:
            resistance[port] = row
        else:
            unported.append({'java': java, **row})
    if not resistance:
        raise SystemExit('no registerHazmat found')

    # ArmorFSB.setRadResist(fullSet) adds (item, fullSet * body fraction) to
    # HazmatRegistry.external, which initDefault registers first; cloneStats
    # repeats it on each cloned piece with that piece's own armor type.
    fractions = [values['helmet'], values['chest'], values['legs'], values['boots']]
    statements = fsb_statements()
    full = {}
    for name, (armor_type, rad, clone, _, line) in statements.items():
        if rad is None and clone in statements:
            rad = statements[clone][1]
        if rad and rad > 0:
            full[name] = (rad * fractions[armor_type], line)
    for name, (value, line) in full.items():
        row = {'value': value, 'source': f'items/ModItemsArmor.java:{line} (setRadResist)'}
        port = plain.get(name)
        if port and port not in resistance:
            resistance[port] = row
        elif not port and not any(u['java'] == 'ModItems.' + name for u in unported):
            unported.append({'java': 'ModItems.' + name, **row})

    mod_items = (JAVA / 'items/ModItems.java').read_text()
    cladding, cladding_unported = {}, []
    for line_no, line in enumerate(mod_items.splitlines(), 1):
        m = re.search(r'(\w+) = new ItemModCladding\(([0-9.]+)\)', line)
        if not m:
            continue
        row = {'value': float(m.group(2)), 'source': f'items/ModItems.java:{line_no}'}
        if m.group(1) in plain:
            cladding[plain[m.group(1)]] = row
        else:
            cladding_unported.append({'java': 'ModItems.' + m.group(1), **row})
    classes, classes_unported = hazard_classes(plain, statements)
    filters = sorted(plain[n] for n in re.findall(r'(\w+) = new ItemFilter\(', mod_items) if n in plain)
    return {
        'schema': 1,
        'about': 'HazmatRegistry.initDefault and ItemModCladding, generated by tools/content-gen/hazmat.py',
        'resistance': dict(sorted(resistance.items())),
        'unported': unported,
        'cladding': dict(sorted(cladding.items())),
        'cladding_unported': cladding_unported,
        'classes': dict(sorted(classes.items())),
        'classes_unported': classes_unported,
        'filters': filters,
    }


def fsb_statements():
    """`name -> (armor type, setRadResist, cloneStats source, setHazardClass, line)` of ModItemsArmor."""
    text = (JAVA / 'items/ModItemsArmor.java').read_text()
    out = {}
    for m in re.finditer(r'(\w+) = new (\w+)\(([^,;]+), (\d)\b(.*?);', text, re.S):
        name, _, _, armor_type, chain = m.groups()
        rad = re.search(r'\.setRadResist\(([0-9.]+)D?', chain)
        clone = re.search(r'\.cloneStats\(\(ArmorFSB\) (\w+)\)', chain)
        group = re.search(r'\.setHazardClass\(ArmorUtil\.(\w+)\)', chain)
        out[name] = (int(armor_type), float(rad.group(1)) if rad else None, clone.group(1) if clone else None,
                     group.group(1) if group else None, text[:m.start()].count('\n') + 1)
    return out


def hazard_classes(plain, statements):
    """ArmorRegistry.hazardClasses: ArmorUtil.register's lines, then the ArmorFSB
    setHazardClass pairs (ArmorUtil.external), which come later and replace."""
    text = (JAVA / 'util/ArmorUtil.java').read_text()
    groups = {name: re.findall(r'HazardClass\.(\w+)', body)
              for name, body in re.findall(r'public static HazardClass\[\] (\w+) = new HazardClass\[\] \{([^}]*)\}', text)}
    body = text[text.index('public static void register()'):text.index('for(Pair<Item, HazardClass[]> pair : external)')]
    rows = []
    for m in re.finditer(r'ArmorRegistry\.registerHazard\(ModItems\.(\w+), ([^;]*)\);', body):
        rows.append((m.group(1), re.findall(r'HazardClass\.(\w+)', m.group(2)),
                     f'util/ArmorUtil.java:{text[:text.index(m.group(0))].count(chr(10)) + 1}'))
    for name, (_, _, _, group, line) in statements.items():
        if group:
            rows.append((name, groups[group], f'items/ModItemsArmor.java:{line} (setHazardClass {group})'))
    classes, unported = {}, {}
    for name, hazards, source in rows:
        row = {'classes': hazards, 'source': source}
        if name in plain:
            classes[plain[name]] = row
        else:
            unported['ModItems.' + name] = row
    return classes, [{'java': k, **v} for k, v in unported.items()]


def main():
    data = json.dumps(extract(), indent=2) + '\n'
    if '--check' in sys.argv:
        if OUT.read_text() != data:
            print(f'{OUT} differs from the Java; run tools/content-gen/hazmat.py', file=sys.stderr)
            sys.exit(1)
        return
    OUT.write_text(data)


if __name__ == '__main__':
    main()
