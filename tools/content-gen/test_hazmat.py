"""crates/ntm-core/data/hazmat.json against HazmatRegistry and ItemModCladding.

The table is generated by hazmat.py; this test re-reads the Java with its
own parsing (material literals by name, body fractions by name), so a slip in
the generator's arithmetic or item resolution cannot hide behind it.
"""
import json
import os
import re
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
JAVA = Path(os.environ.get('NTM_SRC', ROOT.parent / 'ntm-src')) / 'src/main/java/com/hbm'
TABLE = json.loads((ROOT / 'crates/ntm-core/data/hazmat.json').read_text())
IDS = {e['source_variable']: e['id'] for e in json.loads((ROOT / 'content/ids.json').read_text())['entries']
       if e.get('source_variable') and not e.get('source_enum') and not e.get('source_fluid')}
REGISTRY = (JAVA / 'handler/HazmatRegistry.java').read_text()


def double(name):
    return float(re.search(rf'double {name} = ([0-9.]+)D;', REGISTRY).group(1))


class HazmatTable(unittest.TestCase):
    def test_the_file_is_what_the_generator_writes(self):
        import hazmat
        self.assertEqual(TABLE, hazmat.extract())

    def test_every_registration_is_material_times_body_fraction(self):
        calls = re.findall(r'registerHazmat\((ModItems|Items)\.(\w+), (\w+) \* (\w+)\);', REGISTRY)
        self.assertEqual(len(calls), 67)
        for owner, name, material, part in calls:
            value = double(material) * double(part)
            port = ('minecraft:' + name) if owner == 'Items' else IDS.get(name)
            if port:
                self.assertEqual(TABLE['resistance'][port]['value'], value, name)
            else:
                self.assertIn({'java': f'{owner}.{name}', 'value': value},
                              [{'java': u['java'], 'value': u['value']} for u in TABLE['unported']])

    def test_the_literal_registrations(self):
        self.assertEqual(TABLE['resistance']['ntm:gas_mask_m65']['value'], 0.095)
        unported = {u['java']: u['value'] for u in TABLE['unported']}
        if 'gas_mask' not in IDS:
            self.assertEqual(unported['ModItems.gas_mask'], 0.07)
        if 'jackt' not in IDS:
            self.assertEqual(unported['ModItems.jackt'], 0.1)

    def test_the_hazard_classes(self):
        # ArmorUtil.java:39-64 by item, then setHazardClass (external) for FSB helmets.
        self.assertEqual(TABLE['classes']['ntm:gas_mask_filter_mono']['classes'], ['PARTICLE_COARSE', 'GAS_MONOXIDE'])
        self.assertEqual(TABLE['classes']['ntm:mask_piss']['classes'], ['PARTICLE_COARSE', 'GAS_LUNG'])
        self.assertEqual(TABLE['classes']['ntm:liquidator_helmet']['classes'], ['LIGHT', 'SAND'])
        self.assertEqual(TABLE['classes']['ntm:gas_mask_m65']['classes'], ['SAND'])
        self.assertEqual(len(TABLE['classes']) + len(TABLE['classes_unported']),
                         len(re.findall(r'ArmorRegistry\.registerHazard\(ModItems\.', (JAVA / 'util/ArmorUtil.java').read_text()))
                         + len(re.findall(r'\.setHazardClass\(', (JAVA / 'items/ModItemsArmor.java').read_text())))
        self.assertEqual(TABLE['filters'], sorted(IDS[n] for n in re.findall(r'(\w+) = new ItemFilter\(', (JAVA / 'items/ModItems.java').read_text())))

    def test_full_set_resistance_follows_clone_stats(self):
        # ModItemsArmor.java: setRadResist(1D) on t51_helmet, cloned by the other three pieces.
        unported = {u['java']: u['value'] for u in TABLE['unported']}
        if 't51_plate' not in IDS:
            self.assertEqual(unported['ModItems.t51_plate'], 1.0 * 0.4)
            self.assertEqual(unported['ModItems.t51_boots'], 1.0 * 0.1)

    def test_nothing_the_catalog_has_is_left_unported(self):
        for row in TABLE['unported'] + TABLE['cladding_unported'] + TABLE['classes_unported']:
            self.assertNotIn(row['java'].split('.')[1], IDS, row['java'])

    def test_the_claddings(self):
        mods = dict(re.findall(r'(\w+) = new ItemModCladding\(([0-9.]+)\)', (JAVA / 'items/ModItems.java').read_text()))
        self.assertEqual(set(mods), {'cladding_paint', 'cladding_rubber', 'cladding_lead', 'cladding_desh', 'cladding_ghiorsium'})
        rows = {**{IDS.get(k, k): v for k, v in mods.items()}}
        for name, rad in mods.items():
            if name in IDS:
                self.assertEqual(TABLE['cladding'][IDS[name]]['value'], float(rad), name)
        self.assertEqual(len(rows), 5)

    @unittest.skipUnless(__import__('shutil').which('javac'), 'needs a JDK')
    def test_the_java_oracle_fixture_is_current(self):
        import subprocess
        import tempfile
        with tempfile.TemporaryDirectory(dir=os.environ.get('HAZMAT_ORACLE_SCRATCH')) as scratch:
            run = subprocess.run([sys.executable, str(ROOT / 'tools/hazmat-oracle/run.py'), '--scratch', scratch + '/o', '--check'],
                                 capture_output=True, text=True)
        self.assertEqual(run.returncode, 0, run.stderr)

    def test_a_changed_value_is_caught(self):
        import copy
        import hazmat
        mutated = copy.deepcopy(TABLE)
        mutated['resistance']['ntm:steel_plate']['value'] += 1e-9
        self.assertNotEqual(mutated, hazmat.extract())


if __name__ == '__main__':
    unittest.main()
